CREATE TABLE IF NOT EXISTS clientes (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome TEXT,
  email TEXT UNIQUE,
  telefone TEXT,
  senha TEXT,
  criado TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS usuarios_dash (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome TEXT,
  email TEXT UNIQUE,
  senha TEXT,
  perfil TEXT,
  criado TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS profissionais (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome TEXT,
  especialidade TEXT,
  ativo INTEGER DEFAULT 1
);

CREATE TABLE IF NOT EXISTS horarios (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  hora TEXT UNIQUE
);

CREATE TABLE IF NOT EXISTS agendamentos (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cliente_id INTEGER REFERENCES clientes(id) ON DELETE CASCADE,
  prof_id INTEGER REFERENCES profissionais(id),
  modalidade TEXT,
  data DATE,
  hora TEXT,
  status TEXT DEFAULT 'pendente',
  criado TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX IF NOT EXISTS agendamentos_slot_ativo_idx
  ON agendamentos (prof_id, data, hora)
  WHERE status <> 'cancelado';

CREATE TABLE IF NOT EXISTS mensagens (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome TEXT,
  email TEXT,
  telefone TEXT,
  texto TEXT,
  criado TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS user_sessions (
  sid VARCHAR NOT NULL PRIMARY KEY,
  sess JSON NOT NULL,
  expire TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL
);

CREATE INDEX IF NOT EXISTS user_sessions_expire_idx ON user_sessions (expire);

